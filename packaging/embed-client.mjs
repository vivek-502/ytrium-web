#!/usr/bin/env node
/**
 * Embeds the built frontend (`client/dist`) into a generated TypeScript
 * module and writes the Node SEA configuration next to it.
 *
 * Why a module instead of reading files at runtime: a single-file binary has
 * no `client/dist` on disk, and Node's SEA has no supported API for reading
 * injected assets. Generating a module means esbuild inlines the assets into
 * the bundle itself - the runtime just reads one object off `globalThis`.
 *
 * Output (both gitignored, produced by packaging/build-bin.sh):
 *   build/clientAssets.generated.ts   - flags the process, publishes assets
 *   build/sea-config.json             - SEA blob recipe for this machine
 */
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const distDir = path.join(root, 'client', 'dist');
const outDir = path.join(root, 'build');

if (!fs.existsSync(path.join(distDir, 'index.html'))) {
  console.error('error: client/dist/index.html not found - build the client first.');
  process.exit(1);
}

/** Recursively lists every file under `dir` as posix-style relative paths. */
function collect(dir, base = '') {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...collect(path.join(dir, entry.name), rel));
    else out.push(rel);
  }
  return out;
}

const files = collect(distDir);
const assets = {};
let bytes = 0;
for (const rel of files) {
  const buf = fs.readFileSync(path.join(distDir, rel));
  assets[rel] = buf.toString('base64');
  bytes += buf.length;
}

const hash = createHash('sha256');
for (const rel of files) hash.update(rel).update('\0').update(assets[rel]);
const digest = hash.digest('hex').slice(0, 16);

fs.mkdirSync(outDir, { recursive: true });

const modulePath = path.join(outDir, 'clientAssets.generated.ts');
const source = `// GENERATED by packaging/embed-client.mjs - do not edit, do not commit.
// Import order in packaging/sea-entry.ts guarantees this module evaluates
// BEFORE the server: it flags the process as packed (config.ts reads the
// flag), pins production defaults, and publishes the frontend for
// server/src/clientAssets.ts to serve from memory.
process.env.YTTRIUM_PACKED = '1';
process.env.NODE_ENV = process.env.NODE_ENV || 'production';
process.title = 'yttrium';
(globalThis as { __YTTRIUM_CLIENT_ASSETS__?: Record<string, string> }).__YTTRIUM_CLIENT_ASSETS__ = ${JSON.stringify(assets)};
export {};
`;
fs.writeFileSync(modulePath, source);

const seaConfig = {
  main: path.join(outDir, 'sea-bundle.cjs'),
  // Target executable path: build-bin.sh passes the final name so the build
  // produces the deliverable directly (Node 26 `--build-sea` writes it).
  output: process.argv[2] ? path.resolve(process.argv[2]) : path.join(outDir, 'yttrium-sea'),
  disableExperimentalSEAWarning: true,
};
fs.writeFileSync(path.join(outDir, 'sea-config.json'), `${JSON.stringify(seaConfig, null, 2)}\n`);

console.log(`embedded ${files.length} files (${(bytes / 1024).toFixed(0)} KiB, hash ${digest}) -> build/clientAssets.generated.ts`);
